// 取词：当前语言 → zh-CN 兜底 → 键名本身；params 做 {name} 占位替换
export function t(key, params) {
  let s = MESSAGES[currentLang]?.[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/**
 * 启动时读取后端配置确定界面语言（须在首屏渲染前调用）。
 * forceLang：日志窗口这类调不动 get_app_config 的页面，由后端把语言
 * 烘焙进 URL query 传进来。
 */
export async function initI18n(forceLang) {
  if (forceLang && MESSAGES[forceLang]) {
    currentLang = forceLang;
    document.documentElement.lang = currentLang;
    return;
  }
  try {
    const config = await API.getAppConfig();
    if (config?.language && MESSAGES[config.language]) {
      currentLang = config.language;
    }
  } catch { /* 配置读取失败则保持默认语言 */ }
  document.documentElement.lang = currentLang;
}

/** 切换语言：立即生效，写回后端（失败不阻塞界面），然后全量重绘 */
export function applyLang(lang) {
  if (!MESSAGES[lang] || lang === currentLang) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  API.setLanguage(lang).catch(err => console.error('setLanguage failed:', err));
  window.__app?.rerender();
}
